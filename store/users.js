export const mutations = {
    subscribe(state, {id}) {
        const user = state.users.find(el => {
            return el.id === id;
        })
        user.followers += 1;
        user.isFollowedByYou = true;
    },
    unSubscribe(state, {id}) {
        const user = state.users.find(el => {
            return el.id === id;
        })
        user.followers -= 1;
        user.isFollowedByYou = false;
    },
}